export const mobileCharacterAliases = Object.fromEntries(
	Object.values(mobileCharacters)
		.flatMap(item => [item.name, item.localName, ...(item.aliases || [])].filter(Boolean).map(name => [name, item.id]))
);

export function getMobileCharacter(id) {
	return mobileCharacters[id] || null;
}

export function getMobileCharacterByName(name) {
	return mobileCharacters[mobileCharacterAliases[name]] || null;
}

export function getMobileCatalog(id) {
	return mobileCharacterCatalogs[id] || null;
}

export function getMobilePackCharacters(catalogId, packId) {
	const pack = mobileCharacterCatalogs[catalogId]?.packs?.[packId];
	if (!pack) return [];
	return pack.characters.map(id => mobileCharacters[id]).filter(Boolean);
}

function createCharacter(name, nonameId, originPack, options = {}) {
	return {
		id: nonameId,
		name,
		nonameId,
		originPack,
		localName: options.localName || name,
		aliases: options.aliases || [],
		quality: options.quality || null,
		obtain: options.obtain || [],
		price: options.price || {},
		recruit: options.recruit || null,
		czg: options.czg || null,
		duplicate: options.duplicate || {},
	};
}
